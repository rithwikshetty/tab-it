#!/usr/bin/env bash
set -euo pipefail

# Points development builds of the app at the local Docker Supabase stack by
# writing mobile/.env.development.local (git-ignored). Release builds never
# read that file.

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
ENV_FILE="$ROOT_DIR/mobile/.env.development.local"

"$ROOT_DIR/supabase/scripts/assert_local_only.sh"
"$ROOT_DIR/supabase/scripts/verify_local.sh"

status_env="$(supabase status -o env --workdir "$ROOT_DIR" 2>/dev/null)"
publishable_line="$(printf '%s\n' "$status_env" | awk -F= '$1 == "PUBLISHABLE_KEY" { print substr($0, index($0, "=") + 1) }')"
publishable_key="${publishable_line%\"}"
publishable_key="${publishable_key#\"}"

if [[ -z "$publishable_key" ]] || [[ "$publishable_key" != sb_publishable_* ]]; then
  echo "[mobile-local] Refusing: local publishable key was not available." >&2
  exit 1
fi

if [[ "$status_env" == *".supabase.co"* ]]; then
  echo "[mobile-local] Refusing: Supabase status contained a hosted endpoint." >&2
  exit 1
fi

otp_length="$(awk -F' = ' '/^otp_length/ { print $2; exit }' "$ROOT_DIR/supabase/config.toml")"

umask 077
tmp_file="$(mktemp "$ENV_FILE.XXXXXX")"
trap 'rm -f "$tmp_file"' EXIT
{
  echo "# Generated by supabase/scripts/configure_mobile_local.sh. Local stack only; never commit."
  echo "EXPO_PUBLIC_SUPABASE_URL=http://127.0.0.1:54321"
  printf 'EXPO_PUBLIC_SUPABASE_PUBLISHABLE_KEY=%s\n' "$publishable_key"
  printf 'EXPO_PUBLIC_EMAIL_CODE_LENGTH=%s\n' "${otp_length:-6}"
} > "$tmp_file"
mv "$tmp_file" "$ENV_FILE"
trap - EXIT

echo "[mobile-local] Wrote mobile/.env.development.local for the local stack."
echo "[mobile-local] Android emulator: run supabase/scripts/connect_android_emulator.sh so 127.0.0.1:54321 reaches the stack."
